SlipInputBiosKey SlipInputBiosHost_TranslateNormal(uint8_t scan, SlipInputBiosModifiers modifiers, bool extended) {
	if (scan >= sizeof(keyTranslations) / sizeof(keyTranslations[0]))
		return (SlipInputBiosKey){0, 0};
	const SlipBiosKeyTranslations *const entry = &keyTranslations[scan];
	SlipInputBiosKey key;
	if (modifiers.alt)
		key = entry->alt;
	else if (modifiers.control)
		key = entry->control;
	else if (modifiers.shift)
		key = entry->shifted;
	else
		key = entry->normal;
	if (modifiers.capsLock) {
		if (modifiers.shift) {
			if (key.character >= 'A' && key.character <= 'Z')
				key = entry->normal;
		} else if (key.character >= 'a' && key.character <= 'z')
			key = entry->shifted;
	}
	if (extended) {
		enum {
			ENTER_SCAN = 0x1c,
			SLASH_SCAN = 0x35,
			KEYPAD_SCAN = 0xe0,
			ALT_KEYPAD_ENTER_SCAN = 0xa6,
			ALT_KEYPAD_SLASH_SCAN = 0xa4,
			CONTROL_KEYPAD_SLASH_SCAN = 0x95
		};

		if (scan == ENTER_SCAN) {
			if (modifiers.alt)
				key = (SlipInputBiosKey){0, ALT_KEYPAD_ENTER_SCAN};
			else
				key.scanCode = KEYPAD_SCAN;
		} else if (scan == SLASH_SCAN) {
			if (modifiers.alt)
				key = (SlipInputBiosKey){0, ALT_KEYPAD_SLASH_SCAN};
			else if (modifiers.control)
				key = (SlipInputBiosKey){0, CONTROL_KEYPAD_SLASH_SCAN};
			else
				key = (SlipInputBiosKey){'/', KEYPAD_SCAN};
		}
	}
	return key;
}

/* Reference BIOS navigation branch, following its Ctrl-Alt-Delete and Insert
 * bookkeeping. A zero key means add_key does not enqueue a keystroke. */
SlipInputBiosKey SlipInputBiosHost_TranslateNavigation(uint8_t scan, SlipInputBiosModifiers modifiers, bool extended,
                                                       uint8_t *altDigits) {
	const SlipBiosKeyTranslations *const entry = &keyTranslations[scan];
	if (extended) {
		enum { ALT_NAVIGATION_SCAN_OFFSET = 0x50, EXTENDED_CHARACTER = 0xe0 };

		if (modifiers.alt)
			return (SlipInputBiosKey){entry->normal.character,
			                          (uint8_t)(entry->normal.scanCode + ALT_NAVIGATION_SCAN_OFFSET)};
		SlipInputBiosKey key;
		if (modifiers.control)
			key = entry->control;
		else if (modifiers.shift || modifiers.numLock)
			key = entry->shifted;
		else
			key = entry->normal;
		key.character = EXTENDED_CHARACTER;
		return key;
	}
	if (modifiers.alt) {
		*altDigits = (uint8_t)(*altDigits * 10 + entry->alt.character);
		return (SlipInputBiosKey){0, 0};
	}
	if (modifiers.control)
		return entry->control;
	if (modifiers.shift != modifiers.numLock)
		return entry->shifted;
	return entry->normal;
}

/* Reference PC enhanced-keyboard IRQ1 modifier branches. Lock toggles follow
 * CAN_USE_LOCK (the reference build): release toggles, repeated makes do not.
 * Left/right BIOS flag bits are represented by separate native booleans. */
SlipInputBiosModifiers SlipInputBiosHost_UpdateModifiers(SlipInputBiosModifierState *state, uint8_t scan, bool down,
                                                         bool extended) {
	enum {
		CONTROL_SCAN = 0x1d,
		LEFT_SHIFT_SCAN = 0x2a,
		RIGHT_SHIFT_SCAN = 0x36,
		ALT_SCAN = 0x38,
		CAPS_LOCK_SCAN = 0x3a,
		NUM_LOCK_SCAN = 0x45
	};

	switch (scan) {
	case CONTROL_SCAN:
		if (extended)
			state->rightControl = down;
		else
			state->leftControl = down;
		break;
	case LEFT_SHIFT_SCAN:
		state->leftShift = down;
		break;
	case RIGHT_SHIFT_SCAN:
		state->rightShift = down;
		break;
	case ALT_SCAN:
		if (extended)
			state->rightAlt = down;
		else
			state->leftAlt = down;
		break;
	case CAPS_LOCK_SCAN:
		if (!down)
			state->capsLock = !state->capsLock;
		break;
	case NUM_LOCK_SCAN:
		if (!down)
			state->numLock = !state->numLock;
		break;
	}
	return (SlipInputBiosModifiers){state->leftShift || state->rightShift, state->leftControl || state->rightControl,
	                                state->leftAlt || state->rightAlt, state->capsLock, state->numLock};
}
